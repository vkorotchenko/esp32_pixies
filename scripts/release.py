"""Shared versioning and verified GitHub Release packaging."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
REPO = "vkorotchenko/esp32_pixies"
TARGET = "esp32s3_n16r8"
PACKAGE = "com.pixies.controller"
SEMVER = re.compile(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)", re.ASCII)


def version_parts(value):
    if not isinstance(value, str) or not SEMVER.fullmatch(value):
        raise ValueError("Version must be canonical major.minor.patch")
    parts = tuple(map(int, value.split(".")))
    if any(part > 999999 for part in parts):
        raise ValueError("Version component is too large")
    return parts


def validate_version(value):
    if not isinstance(value, dict) or set(value) != {"version", "androidVersionCode"}:
        raise ValueError("Expected version and androidVersionCode")
    version_parts(value["version"])
    code = value["androidVersionCode"]
    if type(code) is not int or not 1 <= code <= 2100000000:
        raise ValueError("Android version code must be 1..2100000000")
    return value


def bumped(value, kind):
    validate_version(value)
    if kind not in ("major", "minor", "patch"):
        raise ValueError("Choose major, minor, or patch")
    parts = list(version_parts(value["version"]))
    index = ("major", "minor", "patch").index(kind)
    parts[index] += 1
    parts[index + 1:] = [0] * (2 - index)
    return validate_version({"version": ".".join(map(str, parts)),
                             "androidVersionCode": value["androidVersionCode"] + 1})


def validate_progress(previous, current):
    validate_version(previous)
    validate_version(current)
    if version_parts(current["version"]) <= version_parts(previous["version"]) or \
            current["androidVersionCode"] <= previous["androidVersionCode"]:
        raise ValueError("Both product version and Android version code must increase")


def read_version():
    return validate_version(json.loads((ROOT / "version.json").read_text()))


def sync(check=False):
    value = read_version()
    version, code = value["version"], value["androidVersionCode"]
    expected = {
        ROOT / "include/version.h": f'#pragma once\n#define PIXIES_VERSION "{version}"\n',
        ROOT / "mobile/src/version.ts":
            f"// Generated by scripts/release.py sync from version.json.\n"
            f"export const APP_VERSION = '{version}';\nexport const APP_VERSION_CODE = {code};\n",
    }
    for name in ("mobile/package.json", "mobile/package-lock.json"):
        path = ROOT / name
        data = json.loads(path.read_text())
        data["version"] = version
        if "packages" in data:
            data["packages"][""]["version"] = version
        expected[path] = json.dumps(data, indent=2) + "\n"
    project = ROOT / "mobile/ios/Pixies.xcodeproj/project.pbxproj"
    text = project.read_text()
    text, count = re.subn(r"MARKETING_VERSION = [^;]+;", f"MARKETING_VERSION = {version};", text)
    if count != 2:
        raise ValueError("Expected two iOS marketing-version settings")
    text, count = re.subn(r"CURRENT_PROJECT_VERSION = [^;]+;", f"CURRENT_PROJECT_VERSION = {code};", text)
    if count != 2:
        raise ValueError("Expected two iOS build-version settings")
    expected[project] = text
    for path, content in expected.items():
        if check:
            if not path.exists() or path.read_text() != content:
                raise ValueError(f"Version drift: {path.relative_to(ROOT)}; run make version-sync")
        else:
            path.write_text(content)
    return value


def run(*args):
    return subprocess.check_output(args, cwd=ROOT, text=True).strip()


def android_tool(name):
    sdk = Path(os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT")
               or Path.home() / ("Library/Android/sdk" if sys.platform == "darwin" else "Android/Sdk"))
    tools = list((sdk / "build-tools").glob(f"*/{name}"))
    if not tools:
        raise ValueError(f"Missing Android build tool {name}; set ANDROID_HOME")
    return str(max(tools, key=lambda p: tuple(int(n) for n in re.findall(r"\d+", p.parent.name))))


def verify_apk(path, value):
    with zipfile.ZipFile(path) as archive:
        if archive.testzip() or archive.getinfo("assets/index.android.bundle").file_size == 0:
            raise ValueError("APK is corrupt or missing its offline JavaScript bundle")
    badging = run(android_tool("aapt"), "dump", "badging", str(path))
    match = re.search(r"package: name='([^']+)' versionCode='(\d+)' versionName='([^']+)'", badging)
    if not match or match.groups() != (PACKAGE, str(value["androidVersionCode"]), value["version"]):
        raise ValueError("APK identity/version does not match version.json")
    certificate = run(android_tool("apksigner"), "verify", "--verbose", "--print-certs", str(path))
    fingerprint = (ROOT / "android-signing.sha256").read_text().strip().lower()
    if not re.fullmatch(r"[a-f0-9]{64}", fingerprint):
        raise ValueError("Missing/invalid public release certificate fingerprint")
    actual = re.findall(
        r"^(?:Signer #\d+|V[1-4](?:\.\d+)? Signer):? certificate SHA-256 digest: ([a-fA-F0-9]{64})$",
        certificate, re.MULTILINE)
    if not re.search(r"^Number of signers: 1$", certificate, re.MULTILINE) or \
            {digest.lower() for digest in actual} != {fingerprint}:
        raise ValueError("APK was not signed by the configured production certificate")
    return fingerprint


def artifact(path, name, version):
    size = path.stat().st_size
    if size == 0:
        raise ValueError(f"Empty artifact: {path}")
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return {"name": name, "size": size, "sha256": digest.hexdigest(),
            "url": f"https://github.com/{REPO}/releases/download/v{version}/{name}"}


def package(args):
    value = sync(check=True)
    dirty = run("git", "status", "--porcelain", "--untracked-files=no")
    if dirty and not args.allow_dirty:
        raise ValueError("Commit source changes before release packaging (local-only: --allow-dirty)")
    source = run("git", "rev-parse", "HEAD")
    firmware, apk = Path(args.firmware).resolve(), Path(args.apk).resolve()
    from check_build import check
    check(firmware)
    fingerprint = verify_apk(apk, value)
    firmware_materials, mobile_materials = Path(args.firmware_materials), Path(args.mobile_materials)
    with zipfile.ZipFile(firmware_materials) as archive:
        identity = json.loads(archive.read("build-identity.json"))
        if identity["commit"] != source or identity["version"] != value["version"] or \
                identity["androidVersionCode"] != value["androidVersionCode"] or \
                (identity.get("localDirtyBuild") and not args.allow_dirty) or \
                identity["firmwareSha256"] != artifact(firmware, "", value["version"])["sha256"]:
            raise ValueError("Firmware build materials do not match the release")
        if archive.testzip():
            raise ValueError("Firmware build materials are corrupt")
    with zipfile.ZipFile(mobile_materials) as archive:
        if not archive.namelist() or archive.testzip():
            raise ValueError("Mobile dependency notices are missing or corrupt")
    version = value["version"]
    manifest = {
        "schemaVersion": 1, "version": version, "commit": source,
        "firmware": {**artifact(firmware, "pixies-firmware.bin", version),
                     "target": TARGET, "bleOtaProtocol": 1},
        "android": {**artifact(apk, "pixies-android.apk", version),
                    "packageName": PACKAGE, "versionCode": value["androidVersionCode"],
                    "certificateSha256": fingerprint},
        "firmwareMaterials": artifact(firmware_materials, "pixies-firmware-materials.zip", version),
        "mobileNotices": artifact(mobile_materials, "pixies-mobile-materials.zip", version),
    }
    if dirty or args.allow_dirty or identity.get("localDirtyBuild"):
        manifest["localDirtyBuild"] = True
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    for path, name in ((firmware, "pixies-firmware.bin"), (apk, "pixies-android.apk"),
                       (firmware_materials, "pixies-firmware-materials.zip"),
                       (mobile_materials, "pixies-mobile-materials.zip")):
        destination = output / name
        if destination.resolve() != path:
            shutil.copyfile(path, destination)
    (output / "release.json").write_text(json.dumps(manifest, indent=2) + "\n")
    sums = "".join(f'{manifest[key]["sha256"]}  {manifest[key]["name"]}\n'
                   for key in ("firmware", "android", "firmwareMaterials", "mobileNotices"))
    sums += f'{hashlib.sha256((output / "release.json").read_bytes()).hexdigest()}  release.json\n'
    (output / "SHA256SUMS").write_text(sums)
    print(f"Verified release {version}: {output}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("sync")
    commands.add_parser("check")
    bump = commands.add_parser("bump")
    bump.add_argument("kind", choices=("major", "minor", "patch"))
    pack = commands.add_parser("package")
    pack.add_argument("--firmware", default=".pio/build/esp32s3_n16r8/firmware.bin")
    pack.add_argument("--apk", default="mobile/android/app/build/outputs/apk/release/app-release.apk")
    pack.add_argument("--firmware-materials", default="dist/materials/pixies-firmware-materials.zip")
    pack.add_argument("--mobile-materials", default="dist/materials/pixies-mobile-materials.zip")
    pack.add_argument("--output", default="dist/release")
    pack.add_argument("--allow-dirty", action="store_true")
    args = parser.parse_args()
    if args.command == "sync":
        sync()
    elif args.command == "check":
        sync(check=True)
    elif args.command == "bump":
        value = bumped(read_version(), args.kind)
        (ROOT / "version.json").write_text(json.dumps(value, indent=2) + "\n")
        sync()
        print(value["version"])
    else:
        package(args)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, subprocess.CalledProcessError, zipfile.BadZipFile, KeyError) as error:
        sys.exit(f"Release error: {error}")
